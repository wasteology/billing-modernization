# Pre-compile all vendor patterns once at module load (avoids re-compiling per call)
_COMPILED_VENDOR_PATTERNS = [
    (vendor, re.compile(pattern))
    for vendor, pattern in VENDOR_PATTERNS.items()
]


def _scan_vendor_patterns(text_upper):
    """Scan pre-compiled VENDOR_PATTERNS against text. Returns first match or None."""
    for vendor, compiled in _COMPILED_VENDOR_PATTERNS:
        if compiled.search(text_upper):
            return vendor
    return None


