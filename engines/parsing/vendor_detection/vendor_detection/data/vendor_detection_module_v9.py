def _check_priority_overrides(text_upper):
    """Check priority overrides for known conflicts. Returns vendor or None.

    These handle cases where two vendor patterns both match the full text.
    Must run on full text (not header) because overrides check for co-occurrence
    of markers that may be spread across the document.
    """
    if _PO_RECOLOGY.search(text_upper) and _PO_WASTE_ZERO.search(text_upper):
        return "Recology"
    if _PO_AM_DISPOSAL_SYS.search(text_upper):
        return "American Disposal Systems"
    if _PO_LRS_WASTE.search(text_upper):
        return "LRS Waste"
    if _PO_WASTE_PRO.search(text_upper) and _PO_LA_GRANDE.search(text_upper):
        return "Waste Pro Oregon"
    if _PO_RELIABLE_PAPER.search(text_upper):
        return "Reliable Paper Recycling"
    if _PO_EMTERRA.search(text_upper):
        if _PO_EMTERRA_ENV.search(text_upper):
            return "Emterra Environmental"
        return "Emterra"
    if _PO_WG_WASTE.search(text_upper) and _PO_GFL.search(text_upper):
        return "WG Waste"
    if _PO_COUNTY_HAULING.search(text_upper) and _PO_WM_MARKERS.search(text_upper):
        return "Waste Management"
    if _PO_WESTERN_WASTE.search(text_upper):
        return "Western Waste Services"
    if _PO_NORTH_LV.search(text_upper):
        return "City of North Las Vegas"
    # v9.4: POC Step 3 HITL-confirmed conflicts (body text references WM/Republic)
    if _PO_A1_TRANSFER.search(text_upper):
        return "A-1 Transfer & Recycling"
    if _PO_WESTCO.search(text_upper):
        return "Westco Trucking"
    if _PO_CAL_WASTE.search(text_upper):
        return "California Waste Recovery Systems"
    if _PO_GARDEN_CITY.search(text_upper):
        return "City of Garden City"
    return None


def detect_vendor(text):
    """Detect vendor from OCR text.

    Priority overrides resolve known multi-vendor conflicts first,
    then full-text pattern scan (first match wins).
    """
    if not text or str(text) == "nan":
        return "OTHER"

    text_upper = normalize_ocr_text(text)

    # Priority overrides — resolve known multi-vendor conflicts
    override = _check_priority_overrides(text_upper)
    if override:
        return override

    # Full-text pattern scan (first match wins)
    return _scan_vendor_patterns(text_upper) or "OTHER"

