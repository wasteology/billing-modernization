OCR_LINEBREAK_PATTERN = re.compile(r'\\\\+[nN]|\\n')

def normalize_ocr_text(text):
    if not text or str(text) == "nan":
        return ""
    text = OCR_LINEBREAK_PATTERN.sub(" ", str(text))
    text = " ".join(text.split())
    return text.upper()

